### 타입 어노테이션(Type Annotation)
# 변수나 함수의 타입을 설명하는 표시
print("===== 1단계: 어노테이션이란? =====")
"""
어노테이션은 실행을 막지 않습니다.
즉, 타입을 강제로 검사하지는 않습니다.
"""

# 기본 변수
age = 30

# 어노테이션 추가
age: int = 30

print(age)

"""
설명:
- age: int 라고 적어두었지만,
- 실제로는 여전히 그냥 변수입니다.
- 타입을 자동으로 검사해주지는 않습니다.
"""


print("\n===== 2단계: 함수에서의 어노테이션 =====")

# 매개변수와 반환값에 타입을 표시할 수 있습니다.
def add(a: int, b: int) -> int:
    return a + b

print(add(3, 5))

"""
설명:

a: int
b: int
-> int  (반환값이 int라는 의미)

하지만 아래처럼 문자열을 넣어도
파이썬은 에러를 내지 않습니다.
"""

print(add("3", "5"))  # 실행됨 (문자열 결합)

"""
정리:
어노테이션은 '설명용'입니다.
파이썬이 강제로 막아주지는 않습니다.
"""


print("\n===== 3단계: 왜 어노테이션을 사용할까? =====")

"""
어노테이션을 사용하는 이유:

1. 코드 가독성 향상
   - 다른 사람이 코드를 읽기 쉬워짐

2. IDE 도움
   - 자동완성, 타입 힌트 제공

3. 협업 시 명확한 타입 전달
"""

def greet(name: str) -> str:
    return "안녕하세요, " + name

print(greet("길동"))


print("\n===== 4단계: 리스트, 딕셔너리 어노테이션 =====")

# 리스트 안에 int가 들어간다는 의미
numbers: list[int] = [1, 2, 3]

# 딕셔너리 타입 지정
person: dict[str, int] = {
    "age": 30,
    "height": 170
}

print(numbers)
print(person)

"""
설명:
list[int] → int만 들어가는 리스트
dict[str, int] → key는 문자열, value는 정수
"""


print("\n===== 5단계: 데이터 분석에서의 활용 =====")

"""
데이터 분석에서 어노테이션은 다음과 같이 사용됩니다.

1. 함수의 입력/출력 타입 명시
2. 복잡한 데이터 구조 설명
3. 협업 시 코드 안정성 향상

예를 들어,
데이터를 처리하는 함수가 있다고 가정해봅시다.
"""

def calculate_bmi(height: float, weight: float) -> float:
    height_m = height / 100
    return weight / (height_m ** 2)

print(calculate_bmi(170, 65))


print("\n===== 최종 정리 =====")

"""
1. 어노테이션은 타입을 설명하는 표시입니다.
2. 실제 실행을 막지는 않습니다.
3. 코드 가독성과 협업에 도움이 됩니다.
4. 데이터 분석 프로젝트에서 함수 구조를 명확히 할 때 유용합니다.
"""